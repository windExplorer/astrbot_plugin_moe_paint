# Build the console WebUI (webui-src -> pages/moe-paint).
# Called by build_zip.ps1 automatically; can also be run standalone.
#
# Steps:
#   1) inject the plugin version from metadata.yaml into webui-src/src/version.ts
#      (metadata.yaml is the single source of truth for the version)
#   2) npm install on first build (only when node_modules is missing)
#   3) vite build -> ../pages/moe-paint/
#
# Keep ASCII-only: PS 5.1 on a non-UTF8 code page can mis-parse CJK comments.

$ErrorActionPreference = "Stop"

if ($PSScriptRoot) {
    $root = $PSScriptRoot
} elseif ($MyInvocation.MyCommand.Path) {
    $root = Split-Path -Parent $MyInvocation.MyCommand.Path
} else {
    $root = (Get-Location).Path
}

$srcDir = Join-Path $root "webui-src"
if (-not (Test-Path (Join-Path $srcDir "package.json"))) {
    Write-Host "ERROR: webui-src/package.json not found" -ForegroundColor Red
    exit 1
}

Push-Location $srcDir
try {
    # --- inject version from metadata.yaml (read as UTF8, file has CJK comments) ---
    $metaPath = Join-Path $root "metadata.yaml"
    $pluginVersion = "dev"
    if (Test-Path $metaPath) {
        $metaRaw = [System.IO.File]::ReadAllText($metaPath, [System.Text.Encoding]::UTF8)
        if ($metaRaw -match '(?m)^\s*version:\s*v?([0-9][^\s#]*)') {
            $pluginVersion = $Matches[1].Trim()
        }
    }
    $versionTs = "// generated by build_webui.ps1 from metadata.yaml - do not edit`nexport const PLUGIN_VERSION = `"$pluginVersion`";`nexport default PLUGIN_VERSION;`n"
    Set-Content -Path (Join-Path $srcDir "src/version.ts") -Value $versionTs -Encoding UTF8
    Write-Host "injected plugin version: $pluginVersion" -ForegroundColor Green

    if (-not (Test-Path (Join-Path $srcDir "node_modules"))) {
        Write-Host "node_modules missing, running npm install ..."
        npm install
        if ($LASTEXITCODE -ne 0) { throw "npm install failed" }
    }

    Write-Host "vite build ..." -ForegroundColor Yellow
    npm run build
    if ($LASTEXITCODE -ne 0) { throw "npm run build failed" }
} finally {
    Pop-Location
}

$pageIndex = Join-Path $root "pages/moe-paint/index.html"
if (-not (Test-Path $pageIndex)) {
    Write-Host "ERROR: build finished but pages/moe-paint/index.html missing" -ForegroundColor Red
    exit 1
}
Write-Host "WebUI built: pages/moe-paint/index.html" -ForegroundColor Green
